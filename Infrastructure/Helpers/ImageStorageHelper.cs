        /// <summary>
        /// ?????? ?? ??? ???? ?????? ??? URL ???
        /// ????: file://, /Images/, /images/, URL ????
        /// </summary>
        public static string NormalizeToPublicUrl(string? imageValue)
        {
            if (string.IsNullOrWhiteSpace(imageValue)) return string.Empty;

            var value = imageValue.Trim();
            var baseUrl = GetPublicBaseUrl();
            var imagesRoot = GetCentralImagesRootPath();

            // ? ???? 1: URL ???? (http://...)
            if (Uri.TryCreate(value, UriKind.Absolute, out var uri))
            {
                // HTTP/HTTPS ? ?????? ??? host ?????? ???? IP ??????
                if (uri.Scheme == Uri.UriSchemeHttp || uri.Scheme == Uri.UriSchemeHttps)
                {
                    var path = uri.AbsolutePath; // /images/Categories/???.jpg
                    if (TryExtractBucketAndFile(path, out var b, out var f))
                        return $"{baseUrl}/images/{b}/{Uri.EscapeDataString(f)}";

                    // ? ???????: ??? ?? ??? ?????????? ?????? ??? host ??????? ??? ????? ??????
                    return $"{baseUrl}{path}";
                }

                // file:// ? ???? ??? URL ???
                if (uri.Scheme == Uri.UriSchemeFile)
                {
                    var localPath = uri.LocalPath;
                    var normRoot  = Path.GetFullPath(imagesRoot);
                    var normLocal = Path.GetFullPath(localPath);

                    if (normLocal.StartsWith(normRoot, StringComparison.OrdinalIgnoreCase))
                    {
                        var rel    = normLocal.Substring(normRoot.Length).TrimStart('\\', '/').Replace('\\', '/');
                        var parts  = rel.Split('/');
                        if (parts.Length >= 2)
                            return $"{baseUrl}/images/{NormalizeBucket(parts[0])}/{Uri.EscapeDataString(parts[1])}";
                    }

                    var fn = Path.GetFileName(localPath);
                    foreach (var bucket in new[] { "Products", "Categories" })
                    {
                        if (File.Exists(Path.Combine(imagesRoot, bucket, fn)))
                            return $"{baseUrl}/images/{bucket}/{Uri.EscapeDataString(fn)}";
                    }
                    return string.Empty;
                }
            }

            // ? ???? 2: ???? ???? /Images/Products/file.jpg ?? /images/Products/file.jpg
            if (TryExtractBucketAndFile(value, out var bk, out var fl))
                return $"{baseUrl}/images/{bk}/{Uri.EscapeDataString(fl)}";

            return string.Empty;
        }

        /// <summary>?????? URL ??? ??? ???? ???? ??? ????? ????? ?? ???????</summary>
        public static string GetLocalFilePath(string? imageUrl)
        {
            if (string.IsNullOrWhiteSpace(imageUrl)) return string.Empty;

            var value = imageUrl.Trim();

            // file:// ? ?????
            if (value.StartsWith("file://", StringComparison.OrdinalIgnoreCase))
            {
                try { return new Uri(value).LocalPath; } catch { return string.Empty; }
            }

            // http://host/images/Bucket/file.jpg
            if (TryExtractBucketAndFile(value, out var bucket, out var fileName))
            {
                var path = Path.Combine(GetCentralImagesRootPath(), bucket, fileName);
                return File.Exists(path) ? path : string.Empty;
            }

            return string.Empty;
        }

