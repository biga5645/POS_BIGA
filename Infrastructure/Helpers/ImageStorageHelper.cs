        [Obsolete("?????? NormalizeToPublicUrl ????? ???")]
        public static string MapToRelativeImagesPath(string? imageValue)
        {
            if (string.IsNullOrWhiteSpace(imageValue)) return string.Empty;
            var value = imageValue.Trim();

            // ??? ??? file:// ? ?????? ?????? ?????? /Images/Bucket/file.jpg
            if (Uri.TryCreate(value, UriKind.Absolute, out var uri) &&
                uri.Scheme == Uri.UriSchemeFile)
            {
                var localPath  = uri.LocalPath;
                var imagesRoot = GetCentralImagesRootPath();
                var normRoot   = Path.GetFullPath(imagesRoot).TrimEnd('\\', '/');
                var normLocal  = Path.GetFullPath(localPath);
                if (normLocal.StartsWith(normRoot, StringComparison.OrdinalIgnoreCase))
                {
                    var rel = normLocal.Substring(normRoot.Length)
                                       .TrimStart('\\', '/')
                                       .Replace('\\', '/');
                    // rel = "Products/file.jpg"
                    var parts = rel.Split('/');
                    if (parts.Length >= 2)
                        return $"/Images/{NormalizeBucket(parts[0])}/{parts[1]}";
                }
            }

            // ??? ??? /Images/ ?????? ? ????? ??? ??
            if (value.StartsWith("/Images/", StringComparison.OrdinalIgnoreCase))
                return value;

            return string.Empty;
        }

