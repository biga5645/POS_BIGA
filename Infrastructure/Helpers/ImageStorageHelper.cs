        private static bool TryExtractBucketAndFile(string path, out string bucket, out string fileName)
        {
            bucket = fileName = string.Empty;
            if (string.IsNullOrWhiteSpace(path)) return false;

            // ????: /images/Bucket/file  ??  /Images/Bucket/file  ??  /uploads/Bucket/file
            var clean = path.TrimStart('/');
            var parts = clean.Split('/', 3); // ? ????? 3 ?????: prefix / bucket / filename
            if (parts.Length < 3) return false;

            var prefix = parts[0].ToLowerInvariant();
            if (prefix != "images" && prefix != "uploads") return false;

            bucket   = NormalizeBucket(parts[1]);
            // ? UnescapeDataString ???? %D9%82... ???????? ??????? ??????????
            fileName = Uri.UnescapeDataString(parts[2]);
            return !string.IsNullOrWhiteSpace(bucket) && !string.IsNullOrWhiteSpace(fileName);
        }

        private static string NormalizeBucket(string? bucket)
        {
            if (string.IsNullOrWhiteSpace(bucket)) return "Products";
            return bucket.Trim().ToLowerInvariant() switch
            {
                "categories" or "category" => "Categories",
                _ => "Products"
            };
        }

        private static string FindWorkspaceRoot(string startPath)
        {
            var current = new DirectoryInfo(startPath);
            while (current != null)
            {
                if (Directory.Exists(Path.Combine(current.FullName, "POS_BIGA")) &&
                    Directory.Exists(Path.Combine(current.FullName, "POS_BIGA.Api")))
                    return current.FullName;
                if (Directory.Exists(Path.Combine(current.FullName, ".git")))
                    return current.FullName;
                current = current.Parent!;
            }
            return AppContext.BaseDirectory;
        }

        private static string BuildSafeFileName(string? input)
        {
            if (string.IsNullOrWhiteSpace(input)) return string.Empty;
            var trimmed = input.Trim();
            foreach (var ch in Path.GetInvalidFileNameChars())
                trimmed = trimmed.Replace(ch, '_');
            return trimmed.Length > 60 ? trimmed[..60] : trimmed;
        }

